    <script>
        const invoiceRange = document.getElementById('invoiceRange');
        const valRange = document.getElementById('valRange');
        const invoiceCountVal = document.getElementById('invoiceCountVal');
        const invoiceValDisplay = document.getElementById('invoiceValDisplay');
        const annualSavings = document.getElementById('annualSavings');
        const hoursSaved = document.getElementById('hoursSaved');

        function updateCalc() {
            const count = parseInt(invoiceRange.value);
            const avgVal = parseInt(valRange.value);
            
            invoiceCountVal.textContent = count + ' invoices';
            invoiceValDisplay.textContent = 'S$' + avgVal.toLocaleString();

            // CC processing saved assuming 60% of invoices previously took CC at ~3.2%
            const ccVolume = count * avgVal * 0.60 * 12;
            const ccFeeSaved = ccVolume * 0.032;
            
            // Hours saved: ~15 mins per 5 invoices on reconciliation
            const monthlyHours = Math.round(count * 0.25);
            hoursSaved.textContent = monthlyHours + ' hours';

            const totalSavings = Math.round(ccFeeSaved + (monthlyHours * 12 * 45)); // $45/hr bookkeeping rate
            annualSavings.textContent = 'S$' + totalSavings.toLocaleString();
        }

        invoiceRange.addEventListener('input', updateCalc);
        valRange.addEventListener('input', updateCalc);
        updateCalc();
    </script>
